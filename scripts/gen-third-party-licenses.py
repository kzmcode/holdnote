#!/usr/bin/env python3
"""Generate THIRD_PARTY_LICENSES.txt for the Rust crates linked into the macOS (arm64) binary.

Walks `cargo metadata` from the `holdnote` package over normal (non-dev, non-build) dependencies
for aarch64-apple-darwin, skips proc-macro crates (not shipped), and embeds each crate's license
files (LICENSE*, COPYING*, NOTICE*) from the cargo registry.
Usage: scripts/gen-third-party-licenses.py [output]   (default: THIRD_PARTY_LICENSES.txt)
"""
import json
import os
import subprocess
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = sys.argv[1] if len(sys.argv) > 1 else os.path.join(ROOT, "THIRD_PARTY_LICENSES.txt")
LICENSE_PREFIXES = ("license", "licence", "copying", "notice", "unlicense")

meta = json.loads(
    subprocess.check_output(
        ["cargo", "metadata", "--format-version", "1", "--locked", "--filter-platform", "aarch64-apple-darwin"],
        cwd=ROOT,
    )
)
pkgs = {p["id"]: p for p in meta["packages"]}
nodes = {n["id"]: n for n in meta["resolve"]["nodes"]}
root = next(p["id"] for p in meta["packages"] if p["name"] == "holdnote" and p["source"] is None)

seen, stack = set(), [root]
while stack:
    pid = stack.pop()
    for dep in nodes[pid]["deps"]:
        if not any(k["kind"] is None for k in dep["dep_kinds"]):
            continue  # dev/build-only dependency
        if dep["pkg"] in seen:
            continue
        p = pkgs[dep["pkg"]]
        if any("proc-macro" in t["kind"] for t in p["targets"]):
            continue  # runs at compile time only
        seen.add(dep["pkg"])
        stack.append(dep["pkg"])


def license_texts(p):
    d = os.path.dirname(p["manifest_path"])
    files = []
    if p.get("license_file"):
        files.append(os.path.join(d, p["license_file"]))
    for f in sorted(os.listdir(d)):
        if f.lower().startswith(LICENSE_PREFIXES) and os.path.isfile(os.path.join(d, f)):
            path = os.path.join(d, f)
            if path not in files:
                files.append(path)
    out = []
    for f in files:
        try:
            with open(f, encoding="utf-8", errors="replace") as fh:
                out.append((os.path.basename(f), fh.read().strip()))
        except OSError:
            pass
    return out


crates = sorted((pkgs[i] for i in seen), key=lambda p: (p["name"], p["version"]))
missing = []
with open(OUT, "w", encoding="utf-8") as w:
    w.write("HoldNote - third-party software notices\n")
    w.write("=" * 40 + "\n\n")
    w.write("HoldNote is distributed under the MIT License (see LICENSE).\n")
    w.write("It includes the following Rust crates. Generated by scripts/gen-third-party-licenses.py.\n")
    w.write("Bundled native components (whisper.cpp, ggml, libomp) are listed in Contents/Resources/licenses/.\n\n")
    w.write("Summary\n-------\n")
    for p in crates:
        w.write(f"{p['name']} {p['version']}: {p.get('license') or 'see license file'}\n")
    for p in crates:
        texts = license_texts(p)
        w.write("\n" + "-" * 78 + "\n")
        w.write(f"{p['name']} {p['version']}  ({p.get('license') or 'see license file'})\n")
        if p.get("repository"):
            w.write(f"{p['repository']}\n")
        if not texts:
            missing.append(f"{p['name']} {p['version']}")
            w.write("\n(No license file shipped with this crate; licensed under the SPDX expression above.)\n")
        for name, text in texts:
            w.write(f"\n[{name}]\n{text}\n")

# Appendix: full standard texts, so crates that only declare an SPDX expression are covered.
def find_text(names):
    for p in crates:
        d = os.path.dirname(p["manifest_path"])
        for n in names:
            f = os.path.join(d, n)
            if os.path.isfile(f):
                with open(f, encoding="utf-8", errors="replace") as fh:
                    return fh.read().strip()
    return None


ZLIB = """This software is provided 'as-is', without any express or implied warranty. In no event will
the authors be held liable for any damages arising from the use of this software.

Permission is granted to anyone to use this software for any purpose, including commercial
applications, and to alter it and redistribute it freely, subject to the following restrictions:

1. The origin of this software must not be misrepresented; you must not claim that you wrote the
   original software. If you use this software in a product, an acknowledgment in the product
   documentation would be appreciated but is not required.
2. Altered source versions must be plainly marked as such, and must not be misrepresented as being
   the original software.
3. This notice may not be removed or altered from any source distribution."""

with open(OUT, "a", encoding="utf-8") as w:
    w.write("\n" + "=" * 78 + "\nAppendix: standard license texts\n" + "=" * 78 + "\n")
    w.write("Crates listed above without their own license file are used under the license named in\n")
    w.write("their SPDX expression; the corresponding standard text follows.\n")
    apache = find_text(["LICENSE-APACHE", "LICENSE-APACHE.md", "LICENSE-APACHE.txt"])
    if apache:
        w.write("\n[Apache License 2.0]\n" + apache + "\n")
    w.write("\n[zlib License]\n" + ZLIB + "\n")
    w.write("\n[Mozilla Public License 2.0]\n")
    w.write("MPL-2.0 crates are used unmodified. Their source code is available from crates.io\n")
    w.write("(https://crates.io/crates/<name>) and the repository URL listed with each crate above.\n")

print(f"wrote {OUT}: {len(crates)} crates", file=sys.stderr)
if missing:
    print("crates without license files: " + ", ".join(missing), file=sys.stderr)
